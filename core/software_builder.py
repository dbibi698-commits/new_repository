"""core/software_builder.py — 🛠️ SOFTWARE BUILDER: boro software banao.

The user describes the software (desktop app, web app, utility tool,
dashboard) and Mark builds the FULL project: file structure + complete
code, TESTS it (runs it), RUNS it on localhost (free port, opened in
Chrome via the no-extension browser driver), FIXES errors (read the
traceback/log, patch the code, restart — max 3 attempts), and offers
ONE-CLICK DEPLOY to Render (push to repo + trigger the Render service,
returning the public link).

HOW CODE IS GENERATED
    ask_fn (Gemini, via core.gemini) is tried first when one is passed in:
    it is asked for a JSON map {path: contents}. Any failure — no key, no
    network, bad JSON — falls back to a REAL stdlib-only template (no
    third-party deps at all), so the localhost run is always verifiable:
    web/dashboard -> http.server app serving a real HTML page; desktop ->
    a Tkinter window; tool -> a CLI script. The fallback is honest about
    being a starter template, never a fake "done".

    BIGGER TEMPLATES (advanced round): when the spec names a stack — or
    the user picks one in the Plugin Settings box — a full real template
    is used instead: Flask dashboard, FastAPI + SQLite REST API, PyQt
    desktop app, static HTML site, Telegram bot (stdlib polling), file
    organizer CLI. Every template ships main.py + requirements.txt +
    README with run instructions. requirements.txt is pip-installed
    best-effort before the run (Flask/FastAPI/PyQt need it); when the
    install fails the reply says so plainly.

KIND-AWARE RUN
    web     -> localhost server (existing fix loop, max 3 attempts)
    tool    -> smoke run: main.py once, output captured; a bot that keeps
             polling counts as running when it printed its startup line
             and was still alive at the 15 s smoke timeout.
    desktop -> py_compile check + the honest run command (a GUI app has
             no localhost server to open).

LOCALHOST SERVERS
    Every running server is tracked in plugin_config["software_builder"]
    ("servers": [{id, project, folder, port, pid, url, started_at}]) with
    stop/restart per server. Ports are picked free — never a port already
    in use; when the preferred port is busy the next free one is used and
    the reply says so.

No Qt, no network to the user's accounts except through the existing
Render/GitHub helpers (tokens from saved config). Every public function
returns a plain value and never raises.
"""
