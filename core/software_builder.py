def is_phone_request(text: str) -> bool:
    return str(text or "").strip().startswith("SOFTWARE_BUILD::")


def handle_phone_request(text: str, ask_fn=None) -> str:
    """SOFTWARE_BUILD::{json: {spec, kind, deploy, repo}} — build it, run
    it on localhost, return the localhost URL + deploy link + status.
    Never raises."""
    try:
        raw = str(text or "").strip()
        if raw.startswith("SOFTWARE_BUILD::"):
            raw = raw[len("SOFTWARE_BUILD::"):]
        try:
            payload = json.loads(raw)
            if not isinstance(payload, dict):
                payload = {"spec": raw}
        except Exception:
            payload = {"spec": raw}
        spec = str(payload.get("spec") or "").strip()
        if not spec:
            return "Ki banabo — spec dao (jemon 'ekta todo dashboard banao')."
        return build_and_run_text(
            spec, kind=str(payload.get("kind") or ""),
            template=str(payload.get("template") or ""),
            deploy=bool(payload.get("deploy")),
            repo=str(payload.get("repo") or ""),
            ask_fn=ask_fn, open_browser=True)
    except Exception as e:
        return f"Phone-er software build korte parlam na: {e}"
