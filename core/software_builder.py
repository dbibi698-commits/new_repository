def classify_spec(spec: str) -> str:
    """web | desktop | tool — keyword-first, dashboard/web wins ties."""
    text = " " + (spec or "").lower() + " "
    for kind in ("web", "desktop", "tool"):
        for kw in _KIND_KEYWORDS[kind]:
            if kw.lower() in text:
                return kind
    return "web"


