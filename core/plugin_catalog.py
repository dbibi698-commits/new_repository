def catalog_key(name: str) -> str:
    """Config key for a catalog entry's enable state.

    Scheme: "catalog_" + slug(name), e.g. "catalog_voice_play_music".
    Stored under config["plugins_enabled"] via memory.config_manager
    get_plugin_enabled()/save_plugin_enabled() — the same opt-out store the
    real plugins use (default ON when absent), so a catalog entry is enabled
    the moment it exists and toggling it needs no restart. The key is derived
    from the display name only; renaming an entry resets its toggle.
    """
    slug = re.sub(r"[^a-z0-9]+", "_", str(name or "").strip().lower()).strip("_")
    return f"catalog_{slug}"


def search_catalog(query: str | None = "") -> list[dict]:
    """Case-insensitive substring search over name/description/trigger.

    Empty/blank query returns all 500 entries (browse mode, like the
    Features overlay's empty-query behaviour). Returns the catalog dicts
    themselves — callers must not mutate them.
    """
    q = str(query or "").strip().lower()
    if not q:
        return list(CATALOG)
    return [e for e in CATALOG
            if q in e["name"].lower()
            or q in e["description"].lower()
            or q in e["trigger"].lower()]


def catalog_stats() -> dict:
    """{"total": 500, "categories": {category: count, ...},
    "tools": {tool: count, ...}} — category counts always sum to total."""
    cats: dict[str, int] = {c: 0 for c in CATEGORIES}
    tools: dict[str, int] = {}
    for e in CATALOG:
        cats[e["category"]] = cats.get(e["category"], 0) + 1
        tools[e["tool"]] = tools.get(e["tool"], 0) + 1
    return {"total": len(CATALOG), "categories": cats, "tools": tools}

