# ── scaffold ─────────────────────────────────────────────────────────────────

def _slug_package(package: str) -> str:
    package = (package or "").strip().lower() or _DEFAULT_PACKAGE
    parts = [p for p in re.split(r"[^a-z0-9_]+", package) if p]
    # A Java package segment may not start with a digit — strip leading
    # digits from EVERY segment (so "123bad" becomes "bad", never
    # "app123bad" which still contains the bad token).
    parts = [re.sub(r"^[0-9]+", "", p) for p in parts]
    parts = [p for p in parts if p]
    if not parts:
        return _DEFAULT_PACKAGE
    return ".".join(parts)


def scaffold_files(package: str, app_name: str,
                    kotlin_code: str = "") -> dict[str, str]:
    """{repo-relative path: contents} for a minimal Android app. Pure
    function, never raises."""
    try:
        pkg = _slug_package(package)
        name = (app_name or "").strip() or _DEFAULT_APP_NAME
        code = (kotlin_code or "").strip()
        if not code:
            code = _MAIN_ACTIVITY_KT.format(package=pkg, app_name=name)
        return {
            "build.gradle.kts": _ROOT_BUILD_KTS.format(
                agp=_KNOWN_AGP_VERSION, kotlin=_KNOWN_KOTLIN_VERSION),
            "settings.gradle.kts": _SETTINGS_KTS.format(app_name=name),
            "gradle/wrapper/gradle-wrapper.properties":
                _GRADLE_WRAPPER_PROPERTIES.format(gradle=_KNOWN_GRADLE_VERSION),
            "app/build.gradle.kts": _APP_BUILD_KTS.format(package=pkg),
            "app/src/main/AndroidManifest.xml": _MANIFEST_XML.format(
                app_name=name),
            "app/src/main/java/" + pkg.replace(".", "/") + "/MainActivity.kt": code,
        }
    except Exception:
        return {}


def write_android_scaffold(folder: str, package: str = _DEFAULT_PACKAGE,
                           app_name: str = _DEFAULT_APP_NAME,
                           kotlin_code: str = "") -> tuple[bool, str, list[str]]:
    """Write the scaffold into `folder`. Returns (ok, message, files).
    Never raises."""
    try:
        root = Path(str(folder or "").strip()).expanduser()
        if not str(folder or "").strip():
            return False, "Folder-er path dao — kothay likhbo?", []
        files = scaffold_files(package, app_name, kotlin_code)
        if not files:
            return False, "Scaffold banate parlam na.", []
        written: list[str] = []
        for rel, content in files.items():
            p = root / rel
            try:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(content, encoding="utf-8")
                written.append(rel)
            except Exception as e:
                return False, f"{rel} likhte parlam na: {e}", written
        return True, (f"✅ Android scaffold likhlam: {len(written)} ta file — "
                      f"{_slug_package(package)} ({app_name}) — "
                      f"build.gradle.kts + MainActivity.kt "
                      f"— folder: {root}"), written
    except Exception as e:
        return False, f"Scaffold likhte parlam na: {e}", []


# ── local toolchain ──────────────────────────────────────────────────────────

def _which_version(cmd: str, args: list[str], timeout: int = 5) -> tuple[bool, str]:
    try:
        exe = shutil.which(cmd)
        if not exe:
            return False, ""
        r = subprocess.run([exe] + args, capture_output=True, text=True,
                           timeout=timeout)
        out = ((r.stdout or "") + "\n" + (r.stderr or "")).strip()
        first = out.splitlines()[0].strip() if out.splitlines() else ""
        return True, first[:120]
    except Exception:
        return False, ""


def local_toolchain_status(project_dir: str = "") -> dict:
    """{java, java_version, gradle, gradle_version, gradlew, gradlew_path}.
    Never raises."""
    try:
        java_ok, java_ver = _which_version("java", ["-version"])
        gradle_ok, gradle_ver = _which_version("gradle", ["--version"])
        gradlew = ""
        if project_dir:
            for name in ("gradlew", "gradlew.bat"):
                cand = Path(str(project_dir)).expanduser() / name
                if cand.is_file():
                    gradlew = str(cand)
                    break
        return {"java": java_ok, "java_version": java_ver,
                "gradle": gradle_ok, "gradle_version": gradle_ver,
                "gradlew": bool(gradlew), "gradlew_path": gradlew}
    except Exception:
        return {"java": False, "java_version": "", "gradle": False,
                "gradle_version": "", "gradlew": False, "gradlew_path": ""}


def local_gradle_build(project_dir: str, task: str = "assembleDebug",
                       timeout: int = 900) -> str:
    """Run a local Gradle build when the toolchain exists. Returns a
    plain-words string. Never raises."""
    try:
        root = Path(str(project_dir or "").strip()).expanduser()
        if not root.is_dir():
            return f"Project folder-ta pelam na: {project_dir or '(khali)'}."
        tc = local_toolchain_status(str(root))
        if not tc.get("java"):
            return ("Local Gradle build hobe na — Java pelam na ei PC-te. "
                    "JDK install koro (17+), na GitHub Actions path use koro "
                    "(repo + workflow dao — ami Actions-e build dibo).")
        if tc.get("gradlew"):
            cmd = [tc["gradlew_path"], task]
        elif tc.get("gradle"):
            cmd = ["gradle", task]
        else:
            return ("Local Gradle build hobe na — Gradle pelam na (na system-e, "
                    "na project-er gradlew). Project-e gradlew thakle dao, na "
                    "GitHub Actions path use koro.")
        try:
            r = subprocess.run(cmd, cwd=str(root), capture_output=True,
                               text=True, encoding="utf-8", errors="replace",
                               timeout=max(60, min(int(timeout or 900), 1800)))
        except subprocess.TimeoutExpired:
            return f"Local Gradle build {timeout}s-e shesh holo na — timeout."
        except Exception as e:
            return f"Local Gradle build chalate parlam na: {e}"
        tail = ((r.stdout or "") + "\n" + (r.stderr or "")).strip()[-1500:]
        if r.returncode == 0:
            apk = list(root.rglob("*.apk"))
            return ("✅ Local Gradle build success holo!"
                    + (f" APK: {apk[0]}" if apk else " (APK file khujlam — "
                       "app/build/outputs/apk/debug-e dekho)") + f"\n{tail[-400:]}")
        return (f"⚠️ Local Gradle build fail holo (exit {r.returncode}). "
                f"Log-er shesh:\n{tail}")
    except Exception as e:
        return f"Local Gradle build chalate parlam na: {e}"


