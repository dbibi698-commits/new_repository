def push_scaffold_to_repo(owner: str, repo: str, folder: str,
                          branch: str = "main",
                          push_fn=None) -> str:
    """Push every scaffold file in `folder` to the repo (Contents API).
    Returns a plain-words summary. Never raises."""
    try:
        owner = (owner or "").strip()
        repo = (repo or "").strip()
        root = Path(str(folder or "").strip()).expanduser()
        if not owner or not repo:
            return "Repo-ta owner/name akare dao."
        if not root.is_dir():
            return f"Folder-ta pelam na: {folder or '(khali)'}."
        if push_fn is None:
            from core import connectors as _conn
            push_fn = _conn.github_push_file
        scaffold = scaffold_files(_DEFAULT_PACKAGE, _DEFAULT_APP_NAME)
        pushed, failed = [], []
        for rel in scaffold:
            p = root / rel
            if not p.is_file():
                failed.append(f"{rel} (file nei)")
                continue
            try:
                content = p.read_text(encoding="utf-8")
            except Exception as e:
                failed.append(f"{rel} (porte parlam na: {e})")
                continue
            try:
                res = push_fn(None, owner, repo, rel, content,
                              f"Mark-LVII: Android scaffold ({rel})")
            except Exception as e:
                res = f"Push korte parlam na: {e}"
            if str(res or "").strip().startswith("✅"):
                pushed.append(rel)
            else:
                failed.append(f"{rel} ({str(res)[:120]})")
        lines = [f"📦 Scaffold push — {owner}/{repo}:"]
        lines.append(f"  ✅ {len(pushed)} ta file push holo"
                     + (f": {', '.join(pushed)}" if pushed else ""))
        if failed:
            lines.append("  ❌ " + "; ".join(failed))
        return "\n".join(lines)
    except Exception as e:
        return f"Scaffold push korte parlam na: {e}"


def build_android(repo: str, workflow: str, ref: str = "main") -> str:
    """GitHub Actions self-healing APK build (the existing build_apk
    path). Returns the self-heal report. Never raises."""
    try:
        from core import apk_selfheal as _sh
        return _sh.build_apk_selfheal(repo, workflow, ref=ref)
    except Exception as e:
        return f"APK build chalate parlam na: {e}"
