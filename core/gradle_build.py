"""core/gradle_build.py — Gradle/Kotlin Android scaffolding + local build.

Mark writes Android code the way it writes everything else: it generates
the files, and the build itself runs where a build can run.

TWO PATHS (honest about both):
  1. GitHub Actions (the real route on this PC — reuse the existing
     build_apk path): write build.gradle.kts + Kotlin sources (+ manifest
     + settings) into a folder, push them to a repo with the GitHub
     Contents API, then dispatch the workflow through the self-healing
     APK builder (core/apk_selfheal.build_apk_selfheal — poll, classify,
     fix, rebuild, max 3 attempts).
  2. Local Gradle (only when the PC actually has the toolchain): detect
     Java + Gradle (or a gradlew wrapper in the project) and run
     `./gradlew assembleDebug` here. When Java/Gradle is absent — the
     usual case on this PC — it says so plainly instead of pretending.

No network calls are made by the scaffold writer itself; pushes and
dispatches go through core/connectors + core/apk_selfheal, whose tokens
come from the saved config exactly like build_apk. Every public function
returns a plain-words string (or a small dict) and never raises. No Qt.
"""
